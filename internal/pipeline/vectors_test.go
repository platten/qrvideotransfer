package pipeline

import (
	"bytes"
	"context"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"flag"
	"os"
	"path/filepath"
	"testing"
	"time"

	"github.com/platten/qrvideotransfer/internal/payload"
	"github.com/platten/qrvideotransfer/internal/video"
)

var update = flag.Bool("update", false, "rewrite testdata/golden/frames.json")

const vectorsPath = "../../testdata/golden/frames.json"

// The fixed input of the frame vectors (FORMAT.md section 13): one file, read-only (a mode every
// system reports alike, 0444 on Windows too), with a fixed modification time.
const (
	vectorName = "vector.txt"
	vectorText = "qrvt frame vector (FORMAT.md section 13): a fixed stream, session and seed, encoded to frames 0 and 1.\n"
	vectorMode = 0o444
)

// vectorRandom is what the encoder draws for the session (8 bytes) and the outer order seed (4).
var vectorRandom = []byte{0x01, 0x23, 0x45, 0x67, 0x89, 0xab, 0xcd, 0xef, 0x24, 0x68, 0xac, 0xe0}

var vectorMTime = time.Date(2026, 11, 19, 0, 0, 0, 0, time.UTC)

// frameVectors is testdata/golden/frames.json.
type frameVectors struct {
	Comment     string        `json:"comment"`
	Name        string        `json:"name"`
	Text        string        `json:"text"`
	Mode        string        `json:"mode"`
	MTime       string        `json:"mtime"`
	Compression string        `json:"compression"`
	Stream      string        `json:"stream"`
	StreamHash  string        `json:"streamSha256"`
	Random      string        `json:"random"`
	Session     string        `json:"session"`
	OrderSeed   string        `json:"orderSeed"`
	Width       int           `json:"width"`
	Height      int           `json:"height"`
	Cell        int           `json:"cell"`
	FPS         int           `json:"fps"`
	InnerCode   uint8         `json:"innerCode"`
	Parity      int           `json:"parity"`
	Frames      []frameVector `json:"frames"`
}

// frameVector is one frame's luma hash.
type frameVector struct {
	Modulation  uint8  `json:"modulation"`
	TotalFrames int    `json:"totalFrames"`
	FrameIndex  int    `json:"frameIndex"`
	Y           string `json:"y"`
}

const vectorsComment = "FORMAT.md section 13 frame vectors: the stream below (the file named, its mode and " +
	"modification time, packed without compression, unsigned and unencrypted), encoded with the session and outer " +
	"order seed below (the encoder's 12 random bytes: the session's 8, big-endian, then the seed's 4) at the size, " +
	"cell, display rate, inner code and parity below, in each modulation, to the SHA-256 of the luma (Y) plane of " +
	"frames 0 and 1, one byte per sample. Generated by the Go encoder through the raw-frame backend " +
	"(go test ./internal/pipeline -run TestFrameVectors -update); regenerated when FORMAT.md changes before v1, " +
	"immutable after."

// vectorInput writes the fixed input file and returns its path.
func vectorInput(t *testing.T) string {
	t.Helper()
	p := filepath.Join(t.TempDir(), vectorName)
	if err := os.WriteFile(p, []byte(vectorText), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := os.Chtimes(p, vectorMTime, vectorMTime); err != nil {
		t.Fatal(err)
	}
	if err := os.Chmod(p, vectorMode); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = os.Chmod(p, 0o600) }) // Windows removes no read-only file
	return p
}

// vectorStream packs the input as the encoder does and returns the stream.
func vectorStream(t *testing.T, in string) []byte {
	t.Helper()
	f, err := os.Create(filepath.Join(t.TempDir(), "stream"))
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = f.Close() }()
	if _, err := payload.Pack(context.Background(), f, payload.PackOptions{Inputs: []string{in}, Compression: payload.CompressNone}); err != nil {
		t.Fatal(err)
	}
	b, err := os.ReadFile(f.Name())
	if err != nil {
		t.Fatal(err)
	}
	return b
}

// TestFrameVectors encodes the fixed stream of testdata/golden/frames.json with the fixed session
// and seed in Gray2, Gray4 and RGB8 at 480p, and compares the SHA-256 of frames 0 and 1's luma
// planes (FORMAT.md section 13). With -update it rewrites the file.
func TestFrameVectors(t *testing.T) {
	in := vectorInput(t)
	stream := vectorStream(t, in)
	sum := sha256.Sum256(stream)
	var g frameVectors
	if !*update {
		b, err := os.ReadFile(vectorsPath)
		if err != nil {
			t.Fatal(err)
		}
		if err := json.Unmarshal(b, &g); err != nil {
			t.Fatal(err)
		}
		if g.Name != vectorName || g.Text != vectorText || g.Mode != "0444" || g.MTime != vectorMTime.Format(time.RFC3339) ||
			g.Random != hex.EncodeToString(vectorRandom) {
			t.Fatal("frames.json's input differs from the test's")
		}
		if g.Width != 848 || g.Height != 480 || g.Cell != 4 || g.FPS != 12 || g.InnerCode != 2 || g.Parity != 20 {
			t.Fatal("frames.json's settings differ from FORMAT.md section 13's")
		}
		if g.Stream != hex.EncodeToString(stream) || g.StreamHash != hex.EncodeToString(sum[:]) {
			t.Errorf("stream %x, want %s", sum, g.StreamHash)
		}
		if len(g.Frames) != 6 {
			t.Fatalf("%d golden frames, want 6", len(g.Frames))
		}
	} else {
		g = frameVectors{Comment: vectorsComment, Name: vectorName, Text: vectorText, Mode: "0444",
			MTime: vectorMTime.Format(time.RFC3339), Compression: "none", Stream: hex.EncodeToString(stream),
			StreamHash: hex.EncodeToString(sum[:]), Random: hex.EncodeToString(vectorRandom),
			Session: hex.EncodeToString(vectorRandom[:8]), OrderSeed: hex.EncodeToString(vectorRandom[8:]),
			Width: 848, Height: 480, Cell: 4, FPS: 12, InnerCode: 2, Parity: 20}
		for _, mod := range []uint8{1, 2, 3} {
			for fi := range 2 {
				g.Frames = append(g.Frames, frameVector{Modulation: mod, FrameIndex: fi})
			}
		}
	}
	for i := 0; i < len(g.Frames); i += 2 {
		mod := g.Frames[i].Modulation
		cfg := EncodeConfig{Inputs: []string{in}, Width: g.Width, Height: g.Height, Cell: g.Cell, FPS: g.FPS,
			Modulation: mod, Inner: g.InnerCode, Parity: g.Parity, Compression: payload.CompressNone,
			Random: bytes.NewReader(vectorRandom), Workers: 1}
		path, res := encodeRaw(t, cfg)
		if res.StreamLen != int64(len(stream)) {
			t.Fatalf("modulation %d: stream of %d bytes, packed %d", mod, res.StreamLen, len(stream))
		}
		frames, _ := readFrames(t, video.NewRaw(), path)
		for j := range 2 {
			gf := &g.Frames[i+j]
			if gf.Modulation != mod || gf.FrameIndex != j {
				t.Fatalf("frames.json entry %d is modulation %d frame %d", i+j, gf.Modulation, gf.FrameIndex)
			}
			y := make([]byte, len(frames[j].Y))
			for k, v := range frames[j].Y {
				y[k] = byte(v)
			}
			h := sha256.Sum256(y)
			if *update {
				gf.TotalFrames, gf.Y = res.Frames, hex.EncodeToString(h[:])
				continue
			}
			if gf.TotalFrames != res.Frames {
				t.Errorf("modulation %d: F = %d, want %d", mod, res.Frames, gf.TotalFrames)
			}
			if got := hex.EncodeToString(h[:]); got != gf.Y {
				t.Errorf("modulation %d frame %d: luma %s, want %s", mod, j, got, gf.Y)
			}
		}
	}
	if *update {
		b, err := json.MarshalIndent(g, "", " ")
		if err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(vectorsPath, append(b, '\n'), 0o600); err != nil {
			t.Fatal(err)
		}
	}
}
