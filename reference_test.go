var updateReference = flag.Bool("update-reference", false,
	"regenerate testdata/golden/reference-v1.mp4 and reference-v1.json (go run ./tools/dev format-vectors)")

// The reference video of format version 1 (FORMAT.md section 13): its golden description, the
// video, and the fixed inputs it is generated from.
const (
	referenceJSON  = "testdata/golden/reference-v1.json"
	referenceVideo = "testdata/golden/reference-v1.mp4"
	referenceName  = "reference.txt"
	referenceMode  = 0o444 // read-only: a mode every system reports alike
	referenceText  = "qrvt reference video, format version 1 (FORMAT.md section 13).\n" +
		"Every later release must decode this video to this file.\n"
)

// referenceRandom is what the encoder draws for the session (8 bytes) and the outer order seed (4).
var referenceRandom = []byte{0x72, 0x65, 0x66, 0x65, 0x72, 0x65, 0x6e, 0x63, 0x00, 0x00, 0x00, 0x01}

var referenceMTime = time.Date(2026, 11, 19, 0, 0, 0, 0, time.UTC)

// referenceProfile is the reference video's profile: 480p, four greys, `normal`.
var referenceProfile = Profile{Width: 848, Height: 480, Cell: 4, FPS: 12, Modulation: Gray4, Protection: Normal, ParityPercent: 20}

// referenceKey is the signing key: the Ed25519 seed of bytes 0 to 31, as the stream vectors use. It
// is a public test key and must never be trusted for anything else.
func referenceKey() ed25519.PrivateKey {
	seed := make([]byte, ed25519.SeedSize)
	for i := range seed {
		seed[i] = byte(i)
	}
	return ed25519.NewKeyFromSeed(seed)
}

// referenceGolden is testdata/golden/reference-v1.json.
type referenceGolden struct {
	Comment       string  `json:"comment"`
	FormatVersion int     `json:"formatVersion"`
	Video         string  `json:"video"`
	VideoBytes    int64   `json:"videoBytes"`
	VideoSHA256   string  `json:"videoSha256"`
	Profile       Profile `json:"profile"`
	Compression   string  `json:"compression"`
	Session       string  `json:"session"`
	Frames        int     `json:"frames"`
	SignerKey     string  `json:"signerKey"`
	File          string  `json:"file"`
	FileBytes     int     `json:"fileBytes"`
	FileSHA256    string  `json:"fileSha256"`
}

const referenceComment = "The reference video of format version 1 (FORMAT.md section 13): every later release " +
	"must decode it to the file named, of the size and SHA-256 given, signed by the key given (the Ed25519 seed of " +
	"bytes 0 to 31). The committed video is what is immutable; it was generated by the embedded engine with one " +
	"worker from fixed inputs (go run ./tools/dev format-vectors), and a regeneration elsewhere need not give the " +
	"same bytes."

// TestReferenceVideo decodes the committed reference video through the public API, with the
// default backend, and checks the file it carries (FORMAT.md section 13). With -update-reference
// it first regenerates the video and its description from the fixed inputs.
func TestReferenceVideo(t *testing.T) {
	key := referenceKey()
	pub := strings.TrimSpace(string(payload.MarshalPublicKey(key.Public().(ed25519.PublicKey))))
	if *updateReference {
		generateReference(t, key, pub)
	}
	var g referenceGolden
	b, err := os.ReadFile(referenceJSON)
	if err != nil {
		t.Fatal(err)
	}
	if err := json.Unmarshal(b, &g); err != nil {
		t.Fatal(err)
	}
	if g.Video != referenceVideo || g.File != referenceName {
		t.Fatalf("reference-v1.json names %s and %s, want %s and %s", g.Video, g.File, referenceVideo, referenceName)
	}
	video, err := os.ReadFile(filepath.FromSlash(g.Video))
	if err != nil {
		t.Fatal(err)
	}
	if sum := sha256.Sum256(video); hex.EncodeToString(sum[:]) != g.VideoSHA256 || int64(len(video)) != g.VideoBytes {
		t.Fatalf("%s: %d bytes, SHA-256 %x; the reference video must never change", g.Video, len(video), sum)
	}
	if g.SignerKey != pub || g.FormatVersion != frame.Version {
		t.Fatalf("reference-v1.json: signer %s, format version %d", g.SignerKey, g.FormatVersion)
	}
	out := t.TempDir()
	rep, err := Decode(context.Background(), DecodeOptions{Recordings: []string{filepath.FromSlash(g.Video)}, OutputDir: out,
		VerifyKeys: [][]byte{[]byte(pub)}})
	if err != nil {
		t.Fatalf("decode: %v", err)
	}
	got, err := os.ReadFile(filepath.Join(out, g.File))
	if err != nil {
		t.Fatal(err)
	}
	if sum := sha256.Sum256(got); hex.EncodeToString(sum[:]) != g.FileSHA256 || len(got) != g.FileBytes {
		t.Errorf("%s: %d bytes, SHA-256 %x, want %d and %s", g.File, len(got), sum, g.FileBytes, g.FileSHA256)
	}
	if rep.Files != 1 || !rep.Signed || !bytes.Equal(rep.SignerKey, key.Public().(ed25519.PublicKey)) ||
		hex.EncodeToString(be64(rep.Session)) != g.Session || rep.FramesTotal != g.Frames {
		t.Errorf("decode report %+v", rep)
	}
}

// generateReference encodes the fixed inputs to the reference video and writes its description.
func generateReference(t *testing.T, key ed25519.PrivateKey, pub string) {
	t.Helper()
	in := filepath.Join(t.TempDir(), referenceName)
	if err := os.WriteFile(in, []byte(referenceText), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := os.Chtimes(in, referenceMTime, referenceMTime); err != nil {
		t.Fatal(err)
	}
	if err := os.Chmod(in, referenceMode); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = os.Chmod(in, 0o600) }) // Windows removes no read-only file
	testRandom = bytes.NewReader(referenceRandom)
	defer func() { testRandom = nil }()
	sign := strings.TrimSpace(string(payload.MarshalPrivateKey(key)))
	rep, err := Encode(context.Background(), EncodeOptions{Inputs: []string{in}, Output: filepath.FromSlash(referenceVideo),
		Profile: referenceProfile, Compression: CompressZstd, SignKey: []byte(sign), Workers: 1, TempDir: t.TempDir()})
	if err != nil {
		t.Fatalf("encode: %v", err)
	}
	video, err := os.ReadFile(filepath.FromSlash(referenceVideo))
	if err != nil {
		t.Fatal(err)
	}
	vs, fs := sha256.Sum256(video), sha256.Sum256([]byte(referenceText))
	g := referenceGolden{Comment: referenceComment, FormatVersion: frame.Version, Video: referenceVideo,
		VideoBytes: int64(len(video)), VideoSHA256: hex.EncodeToString(vs[:]), Profile: rep.Profile, Compression: "zstd",
		Session: hex.EncodeToString(be64(rep.Session)), Frames: rep.Frames, SignerKey: pub, File: referenceName,
		FileBytes: len(referenceText), FileSHA256: hex.EncodeToString(fs[:])}
	b, err := json.MarshalIndent(g, "", " ")
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(referenceJSON, append(b, '\n'), 0o600); err != nil {
		t.Fatal(err)
	}
	t.Logf("%s: %d bytes, %d frames", referenceVideo, len(video), rep.Frames)
}

// be64 returns v big-endian.
func be64(v uint64) []byte {
	b := make([]byte, 8)
	for i := range b {
		b[i] = byte(v >> (56 - 8*i))
	}
	return b
}
